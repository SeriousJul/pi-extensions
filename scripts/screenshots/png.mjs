/**
 * Downsample one 2x RGBA render to 1x by averaging each 2x2 block in
 * linear light (a straight sRGB average darkens antialiased edges).
 * src is row-major RGBA at srcW x srcH, exactly 2x dstW x dstH, and must
 * be fully opaque: resvg composites onto the background color.
 * Returns a row-major RGBA buffer at dstW x dstH.
 */
export function downsample2x(src, srcW, srcH, dstW, dstH) {
	const out = Buffer.alloc(dstW * dstH * 4);
	let d = 0;
	for (let y = 0; y < dstH; y++) {
		const top = (y * 2) * srcW * 4;
		const bot = (y * 2 + 1) * srcW * 4;
		for (let x = 0; x < dstW; x++) {
			const a = top + x * 8;
			const b = a + 4;
			const c = bot + x * 8;
			const e = c + 4;
			if (src[a + 3] + src[b + 3] + src[c + 3] + src[e + 3] !== 1020) {
				throw new Error("resvg produced a non-opaque render; the 2x pass must composite onto the background");
			}
			for (let ch = 0; ch < 3; ch++) {
				const lin =
					SRGB_TO_LINEAR[src[a + ch]] +
					SRGB_TO_LINEAR[src[b + ch]] +
					SRGB_TO_LINEAR[src[c + ch]] +
					SRGB_TO_LINEAR[src[e + ch]];
				out[d + ch] = LINEAR_TO_SRGB[Math.max(0, Math.min(4096, Math.round(lin * 1024)))];
			}
			out[d + 3] = 255;
			d += 4;
		}
	}
	return out;
}

const CRC_TABLE = (() => {
	const table = new Uint32Array(256);
	for (let n = 0; n < 256; n++) {
		let c = n;
		for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
		table[n] = c >>> 0;
	}
	return table;
})();

function crc32(buf) {
	let c = 0xffffffff;
	for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
	return (c ^ 0xffffffff) >>> 0;
}

/** One PNG chunk: 4-byte length, type, data, CRC-32 over type and data. */
function chunk(type, data) {
	const out = Buffer.alloc(12 + data.length);
	out.writeUInt32BE(data.length, 0);
	out.write(type, 4, "ascii");
	data.copy(out, 8);
	out.writeUInt32BE(crc32(out.subarray(4, 8 + data.length)), 8 + data.length);
	return out;
}

/**
 * DEFLATE via pako at level 6 (pure JS, no machine libz). PNG's IDAT wants
 * the zlib-wrapped stream (2-byte header + raw DEFLATE + Adler-32), which
 * is pako's default, not the raw format. The same input always gives the
 * same bytes.
 */
function deflateIdat(data) {
	const d = new Deflate({ level: 6 });
	if (!d.push(data, true)) throw new Error(`pako deflate failed: ${d.msg}`);
	return Buffer.from(d.result);
}

/**
 * Encode one row-major RGBA buffer as an 8-bit truecolor + alpha PNG:
 * filter byte 0 on every row, DEFLATE via pako at level 6. The same
 * pixels always give the same bytes.
 */
export function encodePng(width, height, rgba) {
	const ihdr = Buffer.alloc(13);
	ihdr.writeUInt32BE(width, 0);
	ihdr.writeUInt32BE(height, 4);
	ihdr[8] = 8; // bit depth
	ihdr[9] = 6; // color type: truecolor with alpha
	const stride = width * 4;
	const raw = Buffer.alloc((stride + 1) * height);
	for (let y = 0; y < height; y++) {
		const row = y * (stride + 1);
		raw[row] = 0; // filter: none
		rgba.copy(raw, row + 1, y * stride, (y + 1) * stride);
	}
	const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
	return Buffer.concat([signature, chunk("IHDR", ihdr), chunk("IDAT", deflateIdat(raw)), chunk("IEND", Buffer.alloc(0))]);
}
